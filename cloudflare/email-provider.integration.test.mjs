import test from 'node:test';
import assert from 'node:assert/strict';
import { setup } from './test-support/public-worker.mjs';

test('merchant email configuration on Workers with mocked providers', async t => {
  const { api, ownerToken, managerToken, cron } = await setup(t, 'true');
  const control = body => api('/__email-test-control', { body });
  const { brandId } = await control({});
  const root = `/api/v1/brand-email-settings/${brandId}`;
  const owner = (url, options = {}) => api(url, { ...options, roleToken: ownerToken });
  const save = body => owner(root, { method: 'PUT', body });
  const read = () => owner(root);
  const directTest = (status = 200) => owner(`${root}/test-email`, { body: { recipientEmail: 'mock-recipient@example.com' }, status });
  const business = (status = 200) => owner(`${root}/test-business-email`, { body: { to: 'mock-recipient@example.com' }, status });
  const mode = value => control({ mode: value, resetRate: true });
  await api(root, { roleToken: '', status: 401 });
  await api(root, { roleToken: managerToken, status: 403 });
  await owner('/api/v1/brand-email-settings/11111111-1111-4111-8111-111111111111', { status: 403 });
  await owner(`${root}/test-email`, { body: { recipientEmail: 'bad\r\nmail' }, status: 400 });
  for (const [provider, address, host] of [['GMAIL','salon@gmail.com','smtp.gmail.com'],['QQ','salon@qq.com','smtp.qq.com'],['NETEASE_163','salon@163.com','smtp.163.com']]) {
    await t.test(`${provider}: direct test, verify, enable, disable, rotation`, async () => {
      await mode({});
      const saved = await save({ provider, fromName: 'Salon', fromEmail: address, smtpUsername: address, password: provider === 'GMAIL' ? 'abcd efgh ijkl mnop' : 'synthetic-authorization-code' });
      assert.equal(saved.data.isEnabled, false); assert.equal(saved.data.isVerified, false);
      assert.doesNotMatch(JSON.stringify(saved), /encryptedCredential|oauthDataEncrypted|abcdefghijklmnop|synthetic-authorization-code/);
      await owner(`${root}/enable`, { method: 'PATCH', status: 422 });
      const direct = await directTest(); assert.equal(direct.data.isVerified, true);
      const latest = await control({}); assert.equal(latest.smtp.at(-1).host, host); assert.equal(latest.smtp.at(-1).port, 465); assert.equal(latest.smtp.at(-1).tls, 'on'); assert.equal(latest.encryptedAtRest, true);
      assert.match(latest.smtp.at(-1).from, new RegExp(address.replace('.', '\\.')));
      await owner(`${root}/enable`, { method: 'PATCH' });
      assert.equal((await business()).data.mode, 'MERCHANT');
      await owner(`${root}/disable`, { method: 'PATCH' });
      const socketsBefore = (await control({})).smtp.length;
      assert.equal((await business()).data.mode, 'PLATFORM_DEFAULT');
      assert.equal((await control({})).smtp.length, socketsBefore);
      await save({ provider, fromName: 'New sender name', fromEmail: address, smtpUsername: address });
      assert.equal((await read()).data.setting.isVerified, false);
    });
  }
  await save({ provider: 'GMAIL', fromName: 'Salon', fromEmail: 'salon@gmail.com', smtpUsername: 'salon@gmail.com', password: 'abcdefghijklmnop' });
  for (const [smtp, status, code] of [['connect',502,'EMAIL_CONNECTION_FAILED'],['tls',502,'EMAIL_TLS_FAILED'],['auth',422,'EMAIL_AUTHENTICATION_FAILED'],['uncertain',502,'EMAIL_PROVIDER_FAILED']]) {
    await mode({smtp});
    const before = (await api('/__outbox')).length;
    const error = await directTest(status); assert.equal(error.message, code); assert.doesNotMatch(JSON.stringify(error), /private|abcdefghijklmnop/);
    assert.equal((await api('/__outbox')).length, before);
  }
  await mode({}); await directTest(); await owner(`${root}/enable`, {method:'PATCH'});
  await mode({smtp:'connect'});
  const platformBeforeFailure = (await api('/__outbox')).length;
  await business(502);
  assert.equal((await api('/__outbox')).length, platformBeforeFailure, 'No fallback after merchant failure');
  await api('/api/v1/auth/forgot-password', { body: { email: 'book-now-customer@example.com' } });
  assert.equal((await api('/__outbox')).length, platformBeforeFailure + 1, 'Password reset always uses platform transport');
  await mode({});
  for (let i=0;i<5;i++) await directTest();
  await directTest(429);
  await mode({});
  await save({ provider:'CUSTOM_SMTP', fromName:'Salon', fromEmail:'sender@example.com', smtpHost:'mail.example.com', smtpPort:465, smtpSecure:true, smtpUsername:'sender', password:'synthetic' });
  const custom = await directTest(422); assert.equal(custom.message, 'EMAIL_CUSTOM_SMTP_REQUIRES_NODE_DELIVERY');
  await save({ provider:'RESEND', fromName:'Salon', fromEmail:'onboarding@resend.dev', apiKey:'synthetic-resend-key' });
  assert.equal((await directTest()).data.isVerified, false);
  await owner(`${root}/enable`, {method:'PATCH',status:422});
  await save({ provider:'RESEND', fromName:'Salon', fromEmail:'sender@salon.example', apiKey:'synthetic-resend-key' });
  await mode({existingDomain:true});
  await owner(`${root}/resend/domain`, {body:{domain:'different.example'},status:422});
  const dns = await owner(`${root}/resend/domain`, {body:{domain:'salon.example'}}); assert.equal(dns.data.records[0].type,'TXT');
  await directTest(422);
  await mode({domainVerified:true});
  await owner(`${root}/resend/domain/verify`, {body:{}});
  assert.equal((await directTest()).data.isVerified,true);
  await owner(`${root}/enable`, {method:'PATCH'});
  assert.equal((await business()).data.provider,'RESEND');
  await mode({domainVerified:true,http:'rate'}); await directTest(429);
  assert.equal((await read()).data.setting.isEnabled,false);
  await mode({domainVerified:true,rotateDuringSend:true}); await directTest(409);
  assert.equal((await read()).data.setting.isVerified,false,'An old successful test cannot verify a changed configuration');
  await mode({});
  await save({provider:'MICROSOFT_365',fromName:'Salon',fromEmail:'owner@tenant.example'});
  const start = async () => { const result = await owner(`${root}/microsoft/connect`,{body:{}}); const url=new URL(result.data.authorizationUrl); assert.equal(url.searchParams.get('code_challenge_method'),'S256'); assert.equal(url.searchParams.get('scope'),'offline_access User.Read Mail.Send'); return url.searchParams.get('state'); };
  const callback = (state,status=200) => api(`/api/v1/brand-email-settings/microsoft/callback?state=${state}&code=mock-code`,{roleToken:'',status});
  await callback('invalid',400);
  const expiredState=await start(); await control({expireOAuth:true}); await callback(expiredState,400);
  await mode({identity:'other@tenant.example'}); const wrongState=await start(); await callback(wrongState,422); await callback(wrongState,400);
  await mode({expiresIn:1}); const goodState=await start(); const authorized=await callback(goodState); assert.equal(authorized.data.isVerified,true); assert.doesNotMatch(JSON.stringify(authorized),/mock-access|mock-refresh|oauthDataEncrypted/);
  await callback(goodState,400);
  await owner(`${root}/enable`,{method:'PATCH'});
  await mode({}); await directTest();
  assert.equal((await business()).data.provider,'MICROSOFT_365');
  await mode({graphUnauthorized:true}); await directTest(422);
  assert.equal((await read()).data.setting.isVerified,false);
  await mode({});
  const requests=(await control({})).requests;
  assert.ok(requests.some(r=>r.grant==='authorization_code'&&r.pkce)); assert.ok(requests.some(r=>r.grant==='refresh_token'));
  assert.ok(requests.some(r=>r.host==='graph.microsoft.com'&&r.path.endsWith('/sendMail')&&r.multipart),'Graph uses MIME with HTML and plain-text alternatives');
  await owner(`${root}/microsoft/disconnect`,{method:'DELETE'});
  assert.equal((await read()).data.setting.isVerified,false);
  await owner(`${root}/enable`,{method:'PATCH',status:422});
  await mode({expiresIn:1}); const invalidRefreshState=await start(); await callback(invalidRefreshState);
  await mode({refreshInvalid:true}); await directTest(422); assert.equal((await read()).data.setting.isVerified,false);
  await mode({}); const staleState=await start();
  await save({provider:'MICROSOFT_365',fromName:'Changed',fromEmail:'owner@tenant.example'}); await callback(staleState,409);
  await control({seedOutbox:true}); const sendsBefore=(await control({})).requests.length; await cron();
  const final=await control({}); assert.equal(final.outbox[0].status,'PENDING'); assert.equal(final.requests.length,sendsBefore,'Outbox has no active schedule');
});
